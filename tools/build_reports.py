def build_text():
    r, m, out = load("text"), Tex("TX"), GEN / "text"
    out.mkdir(exist_ok=True)
    links(m, "text")
    ds, q = r["dataset"], r["quality"]
    m["RowsRaw"], m["RowsClean"], m["Removed"] = n(ds["rows_raw"]), n(ds["rows_clean"]), n(ds["rows_raw"] - ds["rows_clean"])
    m["Classes"] = len(ds["classes"])
    m["MissingDesc"], m["DupWithin"], m["MultiSection"], m["NFC"] = n(ds["missing_description"]), n(q["dup_within_section"]), n(q["multi_section_urls"]), n(q["nfc_changed"])
    m["MedTitle"], m["MedDesc"] = n(ds["median_title_len"]), n(ds["median_desc_len"])
    v = ds["vocab"]
    m["VocabUni"], m["VocabBi"], m["VocabChar"] = n(v["TF-IDF 1-gram"]), n(v["TF-IDF 1–2-gram"]), n(v["TF-IDF char 2–5"])
    m["SingleChar"] = n(ds["single_char_syllables_kept"])
    for k, name in [("train", "Train"), ("val", "Val"), ("test", "Test")]:
        m[name] = n(r["split"][k])
    with open(ROOT / "text/data/vnexpress_news.csv", encoding="utf-8") as fh:
        counts = Counter(row["category"] for row in csv.DictReader(fh))
    m["ClassMin"], m["ClassMax"] = min(counts.values()), max(counts.values())

    g = r["grid_val_macro_f1"]
    feats = [("BoW 1-gram", "Bow"), ("TF-IDF 1-gram", "Uni"), ("TF-IDF 1–2-gram", "Bi"), ("TF-IDF char 2–5", "Char")]
    models = [("Multinomial NB", "Nb"), ("Logistic Regression", "Lr"), ("Linear SVM", "Svm"), ("kNN (cosine, k=15)", "Knn")]
    for fk, fs in feats:
        for mk, ms in models:
            m[f"G{fs}{ms}"] = f(g[f"{fk} | {mk}"])
    gv = lambda fk, mk: g[f"{fk} | {mk}"]
    for mk, ms in models[1:]:
        m[f"GainTfidf{ms}"] = sf(gv("TF-IDF 1-gram", mk) - gv("BoW 1-gram", mk))
    bi_gains = [gv("TF-IDF 1–2-gram", mk) - gv("TF-IDF 1-gram", mk) for mk, _ in models]
    m["GainBiMin"], m["GainBiMax"] = sf(min(bi_gains)), sf(max(bi_gains))
    m["GainBiOverBowLr"] = sf(gv("TF-IDF 1–2-gram", "Logistic Regression") - gv("BoW 1-gram", "Logistic Regression"))
    m["GainBiOverBowSvm"] = sf(gv("TF-IDF 1–2-gram", "Linear SVM") - gv("BoW 1-gram", "Linear SVM"))
    best = max(g, key=g.get)
    m["GridBest"], m["GridBestF"] = esc(best.replace(" | ", " + ")), f(g[best])
    write_table(out / "grid.tex", "lrrrr", ["Representation", "Multinomial NB", "Logistic Reg.", "Linear SVM", "kNN (cosine)"],
                [[fk] + [(r"\textbf{%s}" % f(gv(fk, mk))) if f"{fk} | {mk}" == best else f(gv(fk, mk)) for mk, _ in models] for fk, _ in feats])
    m["RandomVal"] = f(r["random_val_macro_f1"])

    bp = r["tuning"]["best_params"]
    m["BestC"] = bp["clf__C"].rstrip("0").rstrip(".")
    m["BestNgram"] = bp["vec__ngram_range"].strip("()").replace(", ", "–")
    m["BestMinDf"], m["CvF"], m["TunedVal"] = bp["vec__min_df"], f(r["tuning"]["cv_macro_f1"]), f(r["tuning"]["val_macro_f1"])

    fl = r["fields_val_macro_f1"]
    m["HeadOnly"], m["LeadOnly"], m["Both"] = f(fl["Headline only"]), f(fl["Lead only"]), f(fl["Headline + lead"])
    m["LeadOverHead"], m["BothOverLead"] = sf(fl["Lead only"] - fl["Headline only"]), sf(fl["Headline + lead"] - fl["Lead only"])
    lc = sorted((int(k), v) for k, v in r["learning_curve"].items())
    mid = min(lc, key=lambda kv: abs(kv[0] - lc[-1][0] / 2))
    m["LcFirstN"], m["LcFirst"], m["LcMidN"], m["LcMid"] = n(lc[0][0]), f(lc[0][1]), n(mid[0]), f(mid[1])
    m["LcLastN"], m["LcLast"], m["LcLastGain"] = n(lc[-1][0]), f(lc[-1][1]), sf(lc[-1][1] - mid[1])

    c = r["comparison"]
    keys = [("Rand", "Stratified random baseline", "Random guess (stratified)"),
            ("Tfidf", "TF-IDF + Linear SVM (tuned)", "TF-IDF 1–3-gram + Linear SVM (tuned)"),
            ("Emb", "Embedding (e5-small) + LogReg", "Embedding (e5-small) + Logistic Regr."),
            ("Hyb", "Hybrid: TF-IDF ⊕ embedding + Linear SVM", "Hybrid: TF-IDF ⊕ embedding + Linear SVM")]
    cell = lambda x: "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f(x)
    for short, k, _ in keys:
        m[f"{short}Val"], m[f"{short}Test"], m[f"{short}Acc"] = cell(c[k]["validation macro-F1"]), cell(c[k]["test macro-F1"]), cell(c[k]["test accuracy"])
    m["GainHyb"] = sf(c[keys[3][1]]["test macro-F1"] - c[keys[1][1]]["test macro-F1"])
    m["GainEmb"] = sf(c[keys[2][1]]["test macro-F1"] - c[keys[1][1]]["test macro-F1"])
    write_table(out / "comparison.tex", "lrrr", ["Approach", "Val. macro-F1", "Test macro-F1", "Test acc."],
                [[label, cell(c[k]["validation macro-F1"]), cell(c[k]["test macro-F1"]), cell(c[k]["test accuracy"])] for _, k, label in keys],
                bold_rows=[3])
    m["FinAcc"], m["FinF"] = f(r["test_accuracy"]), f(r["test_macro_f1"])
    pc = r["per_class_f1"]
    m["BestClass"], m["WorstClass"] = max(pc, key=pc.get), min(pc, key=pc.get)
    m["BestClassF"], m["WorstClassF"] = f(max(pc.values())), f(min(pc.values()))
    items = sorted(pc.items(), key=lambda kv: -kv[1])
    half = (len(items) + 1) // 2
    write_table(out / "perclass.tex", "lrlr", ["Section", "F1", "Section", "F1"],
                [[a[0], f(a[1]), b[0], f(b[1])] for a, b in zip(items[:half], items[half:])])
    write_table(out / "confusions.tex", "llr", ["True section", "Predicted as", "Test errors"],
                [[x["true"], x["predicted"], n(x["errors"])] for x in r["top_confusions"]])
    sims = list(r["centroid_similarity_top"].items())
    pair = lambda k: esc(k.replace(" ~ ", " and "))
    m["SimOnePair"], m["SimOne"], m["SimTwoPair"], m["SimTwo"] = pair(sims[0][0]), f(sims[0][1], 2), pair(sims[1][0]), f(sims[1][1], 2)
    m["NMis"] = n(r["n_misclassified"])
    write_table(out / "misclassified.tex", "Yll", ["Headline (Vietnamese)", "True", "Predicted"],
                [[esc(x["title"]), x["label"], x["predicted"]] for x in r["misclassified_examples"][:8]], width=r"\linewidth")
    write_table(out / "demo.tex", "Yl", ["Headline written by the group (not in the dataset)", "Predicted section"],
                [[esc(x["headline"]), x["predicted section"]] for x in r["demo"]], width=r"\linewidth")
    write_table(out / "topterms.tex", "lY", ["Section", "Top 8 discriminative n-grams (χ², training set)"],
                [[cls, ", ".join(esc(t) for t in terms)] for cls, terms in r["top_terms"].items()], width=r"\linewidth")
    m.write(GEN / "text.tex")


