# ---------- formatting helpers ----------
def esc(s):
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")]:
        s = s.replace(a, b)
    return s


def minus(s):
    return s.replace("-", "−")


def f(x, d=3):
    return minus(f"{x:.{d}f}")


def sf(x, d=3):
    return minus(f"{x:+.{d}f}")


def pct(x, d=1):
    return minus(f"{x * 100:.{d}f}") + r"\%"


def n(x):
    return f"{int(round(x)):,}"


def long_date(iso):
    d = date.fromisoformat(iso)
    return f"{d.day} {d.strftime('%B %Y')}"


class Tex:
    """Collects \\newcommand macros for one part."""

    def __init__(self, prefix):
        self.prefix = prefix
        self.lines = []

    def __setitem__(self, name, value):
        self.lines.append(f"\\newcommand{{\\{self.prefix}{name}}}{{{value}}}")

    def write(self, path):
        path.write_text("% Generated by tools/build_reports.py — do not edit.\n" + "\n".join(self.lines) + "\n",
                        encoding="utf-8")


def write_table(path, colspec, header, rows, bold_rows=(), width=None):
    env = "tabularx" if width else "tabular"
    head = f"\\begin{{{env}}}{{{width}}}{{{colspec}}}" if width else f"\\begin{{tabular}}{{{colspec}}}"
    out = [head, r"\toprule", " & ".join(rf"\hd{{{h}}}" for h in header) + r" \\", r"\midrule"]
    for i, row in enumerate(rows):
        cells = [str(c) for c in row]
        if i in bold_rows:
            cells = [rf"\textbf{{{c}}}" for c in cells]
        out.append(" & ".join(cells) + r" \\")
    out += [r"\bottomrule", f"\\end{{{env}}}"]
    path.write_text("% Generated by tools/build_reports.py — do not edit.\n" + "\n".join(out) + "\n", encoding="utf-8")


def load(part):
    return json.loads((ROOT / part / "results.json").read_text(encoding="utf-8"))


def links(m, part):
    page, notebook, video = f"{PAGES_URL}{part}/", f"{GITHUB_BLOB}/{part}/{NOTEBOOKS[part]}", VIDEO_URLS.get(part)
    m["Page"], m["Notebook"] = rf"\url{{{page}}}", rf"\url{{{notebook}}}"
    m["Video"] = rf"\url{{{video}}}" if video else r"\textcolor{muted}{to be published}"
    video_link = rf"\href{{{video}}}{{Video presentation}}" if video else r"Video: \textcolor{muted}{to be published}"
    m["Links"] = rf"\href{{{page}}}{{Project page}}\quad·\quad\href{{{notebook}}}{{Notebook on GitHub}}\quad·\quad {video_link}"


