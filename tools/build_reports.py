    m["GainF"], m["GainPR"], m["GainROC"] = sf(fin["f1"] - lr["f1"], 2), sf(fin["pr_auc"] - lr["pr_auc"], 2), sf(fin["roc_auc"] - lr["roc_auc"], 2)
