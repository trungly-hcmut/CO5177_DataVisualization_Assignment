def compile_all(only=()):
    BUILD.mkdir(exist_ok=True)
    for doc, target in DOCUMENTS.items():
        if only and doc not in only:
            continue
        for _ in range(4):  # TOC and "Page X of Y" need extra passes
            proc = subprocess.run(["xelatex", "-interaction=nonstopmode", "-halt-on-error", f"-output-directory={BUILD.name}", f"{doc}.tex"],
                                  cwd=REP, capture_output=True, text=True)
            if proc.returncode != 0:
                tail = "\n".join(l for l in proc.stdout.splitlines() if l.startswith("!") or l.startswith("l."))
                sys.exit(f"xelatex failed on {doc}.tex:\n{tail or proc.stdout[-3000:]}")
            if "Rerun" not in (BUILD / f"{doc}.log").read_text(encoding="utf-8", errors="replace"):
                break
        log = (BUILD / f"{doc}.log").read_text(encoding="utf-8", errors="replace")
        missing = log.count("Missing character")
        overfull = log.count("Overfull \\hbox")
        shutil.copy(BUILD / f"{doc}.pdf", target)
        pages = subprocess.run(["pdfinfo", str(target)], capture_output=True, text=True).stdout if shutil.which("pdfinfo") else ""
        npages = next((l.split()[-1] for l in pages.splitlines() if l.startswith("Pages:")), "?")
        print(f"{target.relative_to(ROOT)}: {npages} pages, {missing} missing glyphs, {overfull} overfull lines")


